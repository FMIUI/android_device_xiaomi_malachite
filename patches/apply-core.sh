#!/bin/bash
# Idempotent core fixes the malachite blobs need on Android 17. Re-run on every build.
D=device/xiaomi/malachite/patches
[ -d frameworks/hardware/interfaces/displayservice ] || tar -C frameworks/hardware/interfaces -xzf $D/displayservice.tar.gz
H=system/tools/hidl/build/hidl_interface.go
if [ -f "$H" ] && ! grep -q '"android.frameworks.displayservice@1.0"' "$H"; then
python3 - "$H" <<'PY'
import sys
p = sys.argv[1]; s = open(p).read()
anchor = """	"android.frameworks.sensorservice@1.0":         true,"""; line = """	"android.frameworks.displayservice@1.0":         true,"""
i = s.find(anchor)
if i < 0: sys.exit("malachite: hidl allowlist anchor not found")
j = s.index("\n", i) + 1
open(p, "w").write(s[:j] + line + "\n" + s[j:])
PY
fi
# Android 17 forbids native_app_zygote from finding vendor services, but MediaTek's Mali rule grants it to all domains.
Z=system/sepolicy/private/native_app_zygote.te
if [ -f "$Z" ] && ! grep -q "malachite: mali" "$Z"; then
python3 - "$Z" <<'PY2'
import sys
p = sys.argv[1]; s = open(p).read()
old = "  -webviewupdate_service\n}:service_manager find;"
new = "  -webviewupdate_service\n  -hal_service_type  # malachite: mali\n}:service_manager find;"
if old not in s: sys.exit("malachite: native_app_zygote neverallow not found")
open(p, "w").write(s.replace(old, new, 1))
PY2
fi
# Lineage-only modules the hardware repos expect, provided as root-namespace stand-ins on AOSPA:
#  - org.lineageos.settings.resources: Xiaomi's eSIM switcher; AOSPA ships it as co.aospa.resources
#  - generated_kernel_headers: Lineage's kernel-header module; only referenced by code that malachite
#    doesn't compile (Qualcomm UDFPS extension) or that only needs standard UAPI headers.
C=device/xiaomi/lineage-compat
if [ -f vendor/aospa/target/product/aospa-target.mk ]; then
  mkdir -p "$C"
  cat > "$C/Android.bp" <<'BP'
// Generated by device/xiaomi/malachite/patches/apply-core.sh (AOSPA builds only).
android_library {
    name: "org.lineageos.settings.resources",
    manifest: "AndroidManifest.xml",
    static_libs: ["co.aospa.resources"],
}

cc_library_headers {
    name: "generated_kernel_headers",
    vendor_available: true,
    product_available: true,
    recovery_available: true,
}

// Qualcomm's kernel headers (CLO); MediaTek kernels have none. Users fall back to the standard UAPI headers.
cc_library_headers {
    name: "qti_kernel_headers",
    vendor_available: true,
    product_available: true,
    recovery_available: true,
}
BP
  echo '<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="org.lineageos.settings.resources" />' > "$C/AndroidManifest.xml"
fi
# Android 17 platform policy labels /sys/class/powercap as sysfs_powercap (genfs labels 202604+).
# MediaTek's vendor policy labels the same paths sysfs_therm; identical paths with two labels fail
# precompiled_sepolicy. Where the platform labels them, drop MediaTek's two lines.
G=device/mediatek/sepolicy_vndr/base/vendor/genfs_contexts
if grep -qs "powercap" system/sepolicy/compat/plat_sepolicy_genfs_*.cil && grep -qs "^genfscon sysfs /class/powercap " "$G"; then
  sed -i '/^genfscon sysfs \/class\/powercap /d; /^genfscon sysfs \/devices\/virtual\/powercap /d' "$G"
fi
# AOSPA's recovery minui DRM backend is Qualcomm SDE-only; on MediaTek it brings the panel up (HBM)
# but never draws. Use LineageOS's generic DRM backend instead when the SDE version is present.
M=bootable/recovery/minui
R=device/xiaomi/malachite/patches/recovery-minui
if [ -f vendor/aospa/target/product/aospa-target.mk ] && { ! cmp -s $R/graphics_drm.cpp $M/graphics_drm.cpp || ! cmp -s $R/graphics_drm.h $M/graphics_drm.h; }; then
  cp device/xiaomi/malachite/patches/recovery-minui/graphics_drm.cpp device/xiaomi/malachite/patches/recovery-minui/graphics_drm.h $M/
fi
exit 0
